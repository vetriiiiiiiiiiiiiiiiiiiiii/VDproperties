/** Room id ("bedroom:2", "living") → localised label. */
export function roomLabel(rooms: Record<string, string>, id: string) {
  const [key, num] = id.split(":");
  return num ? `${rooms[key] ?? key} ${num}` : (rooms[key] ?? id);
}
